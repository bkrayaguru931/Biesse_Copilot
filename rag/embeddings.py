# ============================================================
# FULL PIPELINE
# ============================================================

def generate_embeddings(
    chunks: list[dict[str, Any]]
) -> None:
    """
    Generate embeddings for all pending chunks.
    """

    existing = (
        load_existing_embeddings()
    )

    validate_existing_dimensions(
        existing
    )

    pending: list[
        dict[str, Any]
    ] = []

    for chunk in chunks:

        chunk_id = str(
            chunk["metadata"][
                "chunk_id"
            ]
        )

        if chunk_id not in existing:

            pending.append(
                chunk
            )

    print()
    print("=" * 70)
    print("GEMINI EMBEDDING PIPELINE")
    print("=" * 70)

    print(
        f"Model:              "
        f"{EMBEDDING_MODEL}"
    )

    print(
        f"Dimensions:         "
        f"{OUTPUT_DIMENSIONALITY}"
    )

    print(
        f"Total chunks:       "
        f"{len(chunks)}"
    )

    print(
        f"Already embedded:   "
        f"{len(existing)}"
    )

    print(
        f"Remaining:          "
        f"{len(pending)}"
    )

    print(
        f"Max batch size:     "
        f"{MAX_BATCH_SIZE}"
    )

    print(
        f"Max batch tokens:   "
        f"{MAX_BATCH_TOKENS}"
    )

    print(
        f"Target TPM:         "
        f"{TARGET_TOKENS_PER_MINUTE}"
    )

    print()

    if not pending:

        print(
            "All chunks are already embedded."
        )

        return

    batches = build_batches(
        pending
    )

    print(
        f"Planned batches: "
        f"{len(batches)}"
    )

    print()

    for batch_number, batch in enumerate(
        batches,
        start=1,
    ):

        estimated_tokens = sum(
            estimate_chunk_tokens(
                chunk
            )
            for chunk in batch
        )

        first_id = (
            batch[0]["metadata"][
                "chunk_id"
            ]
        )

        last_id = (
            batch[-1]["metadata"][
                "chunk_id"
            ]
        )

        print(
            f"Batch "
            f"{batch_number}/"
            f"{len(batches)}"
            f" | chunks={len(batch)}"
            f" | IDs={first_id}-{last_id}"
            f" | estimated_tokens="
            f"{estimated_tokens}"
        )

        embeddings = (
            generate_batch_embeddings(
                batch
            )
        )

        records = []

        for chunk, embedding in zip(
            batch,
            embeddings,
        ):

            metadata = chunk[
                "metadata"
            ]

            record = {
                "chunk_id": metadata[
                    "chunk_id"
                ],
                "text": chunk[
                    "text"
                ],
                "embedding": embedding,
                "metadata": {
                    "source": metadata.get(
                        "source"
                    ),
                    "start_page": metadata.get(
                        "start_page"
                    ),
                    "end_page": metadata.get(
                        "end_page"
                    ),
                    "section": metadata.get(
                        "section"
                    ),
                    "word_count": metadata.get(
                        "word_count"
                    ),
                },
            }

            records.append(
                record
            )

        append_embeddings(
            records
        )

        print(
            f"  Saved "
            f"{len(records)} embeddings."
        )

        processed = sum(
            len(batch)
            for batch in batches[
                :batch_number
            ]
        )

        print(
            f"  Progress: "
            f"{processed}/"
            f"{len(pending)}"
        )

        # ----------------------------------------------------
        # Rate-limit delay
        # ----------------------------------------------------

        if batch_number < len(
            batches
        ):

            delay = (
                calculate_batch_delay(
                    estimated_tokens
                )
            )

            print(
                f"  Waiting "
                f"{delay:.1f}s "
                "to stay below "
                "the TPM limit..."
            )

            time.sleep(
                delay
            )

        print()

    final_embeddings = (
        load_existing_embeddings()
    )

    print("=" * 70)
    print("EMBEDDING PIPELINE COMPLETE")
    print("=" * 70)

    print(
        f"Total embeddings saved: "
        f"{len(final_embeddings)}"
    )

    print(
        f"Expected embeddings: "
        f"{len(chunks)}"
    )

    print(
        f"Output: "
        f"{EMBEDDINGS_FILE}"
    )

    print()

    if len(final_embeddings) == len(
        chunks
    ):

        print(
            "SUCCESS: All chunks have "
            "embeddings."
        )

    else:

        print(
            "WARNING: Embedding count "
            "does not yet match chunk count."
        )

        print(
            "You can safely rerun the "
            "pipeline to continue."
        )


# ============================================================
# INSPECTION
# ============================================================

def inspect_existing_embeddings() -> None:
    """
    Print useful information about the
    current embeddings.jsonl.
    """

    if not EMBEDDINGS_FILE.exists():

        print(
            "embeddings.jsonl does not exist."
        )

        return

    existing = (
        load_existing_embeddings()
    )

    print()
    print("=" * 70)
    print("EXISTING EMBEDDINGS")
    print("=" * 70)

    print(
        f"Unique chunk IDs: "
        f"{len(existing)}"
    )

    dimensions: set[int] = set()

    for record in existing.values():

        embedding = record.get(
            "embedding"
        )

        if embedding:

            dimensions.add(
                len(embedding)
            )

    print(
        f"Dimensions found: "
        f"{sorted(dimensions)}"
    )

    chunk_ids = list(
        existing.keys()
    )

    if chunk_ids:

        print(
            f"First chunk ID: "
            f"{chunk_ids[0]}"
        )

        print(
            f"Last chunk ID: "
            f"{chunk_ids[-1]}"
        )

    print("=" * 70)


# ============================================================
# MAIN
# ============================================================

def main() -> None:

    parser = argparse.ArgumentParser(
        description=(
            "Generate Gemini Embedding 2 "
            "vectors for the Biesse RAG "
            "knowledge base."
        )
    )

    parser.add_argument(
        "--test",
        action="store_true",
        help=(
            "Embed only the first two "
            "chunks."
        ),
    )

    parser.add_argument(
        "--reset",
        action="store_true",
        help=(
            "Back up existing embeddings "
            "and regenerate everything."
        ),
    )

    parser.add_argument(
        "--inspect",
        action="store_true",
        help=(
            "Inspect existing embeddings "
            "without generating anything."
        ),
    )

    args = parser.parse_args()

    # Inspection does not require chunks.
    if args.inspect:

        inspect_existing_embeddings()

        return

    chunks = load_chunks()

    print(
        f"Loaded {len(chunks)} chunks."
    )

    # Reset before loading existing embeddings.
    if args.reset:

        reset_embeddings()

    if args.test:

        test_embeddings(
            chunks
        )

    else:

        generate_embeddings(
            chunks
        )


# ============================================================
# ENTRY POINT
# ============================================================

if __name__ == "__main__":
    main()