"""
Gemini Embedding Pipeline for the Biesse RAG System.

Input:
    knowledge_base/processed/chunks.jsonl

Output:
    knowledge_base/processed/embeddings.jsonl

Pipeline:

    chunks.jsonl
        |
        v
    Gemini Embedding 2
        |
        v
    embeddings.jsonl
        |
        v
    ChromaDB

Design goals:
    - Gemini Embedding 2
    - 1536-dimensional vectors
    - Retrieval-optimized document formatting
    - Conservative free-tier token throttling
    - Batch processing
    - Retry handling
    - Resumable execution
    - Dimension consistency checks
    - Test mode
    - Safe reset mode
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import time
from datetime import datetime
from pathlib import Path
from typing import Any

from dotenv import load_dotenv
from google import genai
from google.genai import types


# ============================================================
# CONFIGURATION
# ============================================================

load_dotenv()

API_KEY = os.getenv("GEMINI_API_KEY")

if not API_KEY:
    raise RuntimeError(
        "GEMINI_API_KEY is not set.\n"
        "Add GEMINI_API_KEY=your_key to the .env file."
    )


# Gemini Embedding 2
EMBEDDING_MODEL = "gemini-embedding-2"

# Recommended reduced dimensionality for this POC.
# Google supports 768, 1536 and 3072.
OUTPUT_DIMENSIONALITY = 1536


# ------------------------------------------------------------
# Rate limiting
# ------------------------------------------------------------


TARGET_TOKENS_PER_MINUTE = 20_000

# Maximum estimated tokens sent in one API request.
#
# input-token constraints.
MAX_BATCH_TOKENS = 6_000

# Hard maximum number of chunks in one request.
MAX_BATCH_SIZE = 5

# Minimum delay between successful requests.
MIN_BATCH_DELAY_SECONDS = 5


# ------------------------------------------------------------
# Retry configuration
# ------------------------------------------------------------

MAX_RETRIES = 3

# For 429 errors, wait at least one minute because the
# free-tier problem is TPM-based.
RATE_LIMIT_RETRY_DELAY = 60

# Normal transient errors use exponential backoff.
INITIAL_RETRY_DELAY = 2


# ============================================================
# PATHS
# ============================================================

PROJECT_ROOT = (
    Path(__file__).resolve().parent.parent
)

PROCESSED_DIR = (
    PROJECT_ROOT
    / "knowledge_base"
    / "processed"
)

CHUNKS_FILE = (
    PROCESSED_DIR
    / "chunks.jsonl"
)

EMBEDDINGS_FILE = (
    PROCESSED_DIR
    / "embeddings.jsonl"
)


# ============================================================
# GEMINI CLIENT
# ============================================================

client = genai.Client(
    api_key=API_KEY
)


# ============================================================
# CHUNK LOADING
# ============================================================

def load_chunks() -> list[dict[str, Any]]:
    """
    Load chunks generated by chunker.py.

    Expected structure:

    {
        "text": "...",
        "metadata": {
            "source": "...",
            "start_page": 1,
            "end_page": 23,
            "section": "...",
            "word_count": 877,
            "chunk_id": 0
        }
    }
    """

    if not CHUNKS_FILE.exists():
        raise FileNotFoundError(
            f"Could not find:\n{CHUNKS_FILE}\n\n"
            "Run chunker.py first."
        )

    chunks: list[dict[str, Any]] = []

    with CHUNKS_FILE.open(
        "r",
        encoding="utf-8",
    ) as file:

        for line_number, line in enumerate(
            file,
            start=1,
        ):

            line = line.strip()

            if not line:
                continue

            try:
                chunk = json.loads(line)

            except json.JSONDecodeError as error:

                raise ValueError(
                    f"Invalid JSON on line "
                    f"{line_number} of "
                    f"{CHUNKS_FILE}"
                ) from error

            # Validate top-level structure.
            if "text" not in chunk:
                raise ValueError(
                    f"Chunk on line {line_number} "
                    "does not contain 'text'."
                )

            if "metadata" not in chunk:
                raise ValueError(
                    f"Chunk on line {line_number} "
                    "does not contain 'metadata'."
                )

            metadata = chunk["metadata"]

            if "chunk_id" not in metadata:
                raise ValueError(
                    f"Chunk on line {line_number} "
                    "does not contain "
                    "'metadata.chunk_id'."
                )

            chunks.append(chunk)

    return chunks


# ============================================================
# EXISTING EMBEDDINGS
# ============================================================

def load_existing_embeddings() -> dict[str, dict[str, Any]]:
    """
    Load already generated embeddings.

    Returns:

        {
            "0": {...},
            "1": {...},
            ...
        }
    """

    existing: dict[str, dict[str, Any]] = {}

    if not EMBEDDINGS_FILE.exists():
        return existing

    with EMBEDDINGS_FILE.open(
        "r",
        encoding="utf-8",
    ) as file:

        for line_number, line in enumerate(
            file,
            start=1,
        ):

            line = line.strip()

            if not line:
                continue

            try:
                record = json.loads(line)

            except json.JSONDecodeError:

                print(
                    f"Warning: skipping invalid JSON "
                    f"on embeddings.jsonl line "
                    f"{line_number}"
                )

                continue

            chunk_id = record.get(
                "chunk_id"
            )

            if chunk_id is None:
                continue

            existing[
                str(chunk_id)
            ] = record

    return existing


# ============================================================
# EMBEDDING VALIDATION
# ============================================================

def validate_existing_dimensions(
    existing: dict[str, dict[str, Any]]
) -> None:
    """
    All existing embeddings should have the
    dimensionality that is currently expected.

    This prevents mixing 3072-dimensional and
    1536-dimensional vectors.
    """

    if not existing:
        return

    dimensions_found: set[int] = set()

    for record in existing.values():

        embedding = record.get(
            "embedding"
        )

        if not embedding:
            continue

        dimensions_found.add(
            len(embedding)
        )

    if not dimensions_found:
        return

    if dimensions_found != {
        OUTPUT_DIMENSIONALITY
    }:

        raise RuntimeError(
            "\nExisting embeddings have "
            f"dimensions: {sorted(dimensions_found)}\n"
            f"But this pipeline is configured for "
            f"{OUTPUT_DIMENSIONALITY} dimensions.\n\n"
            "Do NOT mix embedding dimensions.\n"
            "Use:\n\n"
            "    python rag\\embeddings.py --reset\n\n"
            "to back up the old embeddings and "
            "regenerate them consistently."
        )


# ============================================================
# SAVE EMBEDDINGS
# ============================================================

def append_embeddings(
    records: list[dict[str, Any]]
) -> None:
    """
    Append generated records to embeddings.jsonl.
    """

    PROCESSED_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    with EMBEDDINGS_FILE.open(
        "a",
        encoding="utf-8",
    ) as file:

        for record in records:

            file.write(
                json.dumps(
                    record,
                    ensure_ascii=False,
                )
                + "\n"
            )


# ============================================================
# RESET EXISTING EMBEDDINGS
# ============================================================

def reset_embeddings() -> None:
    """
    Back up the current embeddings.jsonl and start fresh.

    This is necessary when changing embedding dimensions.
    """

    if not EMBEDDINGS_FILE.exists():

        print(
            "No existing embeddings.jsonl found."
        )

        return

    timestamp = (
        datetime.now()
        .strftime(
            "%Y%m%d_%H%M%S"
        )
    )

    backup_file = (
        PROCESSED_DIR
        / f"embeddings_backup_{timestamp}.jsonl"
    )

    shutil.move(
        EMBEDDINGS_FILE,
        backup_file,
    )

    print()
    print(
        "Existing embeddings backed up to:"
    )

    print(
        backup_file
    )

    print()


# ============================================================
# TEXT NORMALIZATION
# ============================================================

def normalize_text(
    text: str
) -> str:
    """
    Normalize whitespace while preserving
    the actual document content.
    """

    return " ".join(
        text.split()
    )


# ============================================================
# RETRIEVAL DOCUMENT FORMAT
# ============================================================

def prepare_document(
    chunk: dict[str, Any]
) -> str:
    """
    Prepare a chunk for Gemini Embedding 2
    retrieval embedding.

    Google recommends the structure:

        title: {title} | text: {content}

    We use the document section as the title.
    """

    metadata = chunk[
        "metadata"
    ]

    section = (
        metadata.get("section")
        or "none"
    )

    text = normalize_text(
        chunk["text"]
    )

    return (
        f"title: {section} | "
        f"text: {text}"
    )


# ============================================================
# TOKEN ESTIMATION
# ============================================================

def estimate_tokens(
    text: str
) -> int:
    """
    Approximate token count.

    This is intentionally conservative.

    For English technical text, a rough
    chars/4 estimate is useful for rate
    limiting. We add a small safety margin.
    """

    normalized = normalize_text(
        text
    )

    if not normalized:
        return 0

    estimated = max(
        1,
        len(normalized) // 4,
    )

    # 10% safety margin.
    return int(
        estimated * 1.10
    )


def estimate_chunk_tokens(
    chunk: dict[str, Any]
) -> int:
    """
    Estimate the tokens that will be sent
    to Gemini for one chunk.
    """

    prepared = prepare_document(
        chunk
    )

    return estimate_tokens(
        prepared
    )


# ============================================================
# BUILD RATE-LIMITED BATCHES
# ============================================================

def build_batches(
    chunks: list[dict[str, Any]]
) -> list[list[dict[str, Any]]]:
    """
    Build batches using both:

        - maximum chunks
        - estimated token budget

    This prevents large requests from blowing
    through the free-tier TPM limit.
    """

    batches: list[
        list[dict[str, Any]]
    ] = []

    current_batch: list[
        dict[str, Any]
    ] = []

    current_tokens = 0

    for chunk in chunks:

        chunk_tokens = (
            estimate_chunk_tokens(
                chunk
            )
        )

        # If a single chunk exceeds our target,
        # send it individually.
        if chunk_tokens > MAX_BATCH_TOKENS:

            if current_batch:

                batches.append(
                    current_batch
                )

                current_batch = []
                current_tokens = 0

            batches.append(
                [chunk]
            )

            continue

        would_exceed_tokens = (
            current_tokens
            + chunk_tokens
            > MAX_BATCH_TOKENS
        )

        would_exceed_size = (
            len(current_batch)
            >= MAX_BATCH_SIZE
        )

        if (
            current_batch
            and (
                would_exceed_tokens
                or would_exceed_size
            )
        ):

            batches.append(
                current_batch
            )

            current_batch = []
            current_tokens = 0

        current_batch.append(
            chunk
        )

        current_tokens += (
            chunk_tokens
        )

    if current_batch:

        batches.append(
            current_batch
        )

    return batches


# ============================================================
# GEMINI EMBEDDING REQUEST
# ============================================================

def generate_batch_embeddings(
    chunks: list[dict[str, Any]]
) -> list[list[float]]:
    """
    Generate one embedding for each chunk.

    Gemini Embedding 2 returns separate embeddings
    when each input is wrapped in its own Content object.
    """

    if not chunks:
        return []

    contents = []

    for chunk in chunks:

        text = prepare_document(
            chunk
        )

        contents.append(
            types.Content(
                parts=[
                    types.Part.from_text(
                        text=text
                    )
                ]
            )
        )

    for attempt in range(
        MAX_RETRIES
    ):

        try:

            response = (
                client.models.embed_content(
                    model=EMBEDDING_MODEL,
                    contents=contents,
                    config=types.EmbedContentConfig(
                        output_dimensionality=(
                            OUTPUT_DIMENSIONALITY
                        )
                    ),
                )
            )

            embeddings = [
                embedding.values
                for embedding
                in response.embeddings
            ]

            if len(embeddings) != len(
                chunks
            ):

                raise RuntimeError(
                    f"Expected "
                    f"{len(chunks)} embeddings, "
                    f"received "
                    f"{len(embeddings)}."
                )

            # Verify dimensions immediately.
            for index, embedding in enumerate(
                embeddings
            ):

                if len(embedding) != (
                    OUTPUT_DIMENSIONALITY
                ):

                    raise RuntimeError(
                        f"Chunk index {index} "
                        f"returned "
                        f"{len(embedding)} "
                        "dimensions instead of "
                        f"{OUTPUT_DIMENSIONALITY}."
                    )

            return embeddings

        except Exception as error:

            error_text = str(
                error
            )

            is_rate_limit = (
                "429" in error_text
                or "RESOURCE_EXHAUSTED"
                in error_text
            )

            if is_rate_limit:

                if attempt >= (
                    MAX_RETRIES - 1
                ):

                    raise RuntimeError(
                        "Gemini rate limit "
                        "persisted after "
                        f"{MAX_RETRIES} attempts.\n\n"
                        "The free-tier TPM limit "
                        "may still be exhausted. "
                        "Wait and rerun the "
                        "pipeline; existing "
                        "embeddings will be "
                        "skipped."
                    ) from error

                print()
                print(
                    "429 RESOURCE_EXHAUSTED."
                )

                print(
                    "Waiting "
                    f"{RATE_LIMIT_RETRY_DELAY} "
                    "seconds before retry..."
                )

                time.sleep(
                    RATE_LIMIT_RETRY_DELAY
                )

                continue

            # Non-rate-limit error.
            if attempt >= (
                MAX_RETRIES - 1
            ):

                raise RuntimeError(
                    "Gemini embedding request "
                    "failed after "
                    f"{MAX_RETRIES} attempts."
                ) from error

            delay = (
                INITIAL_RETRY_DELAY
                * (
                    2 ** attempt
                )
            )

            print(
                f"Request failed: {error}"
            )

            print(
                f"Retrying in {delay} "
                "seconds..."
            )

            time.sleep(
                delay
            )

    raise RuntimeError(
        "Unexpected embedding failure."
    )


# ============================================================
# THROTTLING
# ============================================================

def calculate_batch_delay(
    estimated_tokens: int
) -> float:
    """
    Calculate how long to wait after a batch.

    Target:
        approximately 20K tokens/minute

    This keeps us comfortably below the
    observed 30K TPM free-tier limit.
    """

    if estimated_tokens <= 0:
        return MIN_BATCH_DELAY_SECONDS

    seconds_needed = (
        estimated_tokens
        / TARGET_TOKENS_PER_MINUTE
        * 60
    )

    return max(
        MIN_BATCH_DELAY_SECONDS,
        seconds_needed,
    )


